import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
import {captureLayouts} from './visual-checks';

test('teacher publishes a fresh quiz, enrolled student receives AI feedback, and weak topics move first',async({page})=>{
  test.setTimeout(120000);
  test.skip(!process.env.DATABASE_URL||!process.env.GEMINI_API_KEY||!process.env.DEMO_PASSWORD,'Requires connected database and Gemini.');
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  const password='browser-classroom-password-123';
  await page.request.post('/api/auth/login',{data:{username:'teacher_demo',password:process.env.DEMO_PASSWORD}});
  const parent=(await (await page.request.get('/api/teacher/invitation')).json()).data;
  const owner='class_teacher_'+randomUUID().slice(0,8);
  const teacher=await page.request.post('/api/auth/signup',{data:{username:owner,password,role:'teacher',invite_code:parent.teacher_code}});
  expect(teacher.status()).toBe(201);
  const codes=(await (await page.request.get('/api/teacher/invitation')).json()).data;
  await page.goto('/teacher');
  await page.getByRole('button',{name:'Show class codes'}).click();
  await expect(page.getByRole('heading',{name:'Student enrollment code',exact:true})).toBeVisible();
  await expect(page.getByRole('heading',{name:'Teacher referral code',exact:true})).toBeVisible();
  await page.getByRole('link',{name:'Subjects & quizzes',exact:true}).click();
  await page.getByText('Add a subject',{exact:true}).click();
  await page.getByLabel('Subject name').fill('Basic Maths');
  await page.getByLabel('About this subject').fill('Reasoning with numbers.');
  await page.getByRole('button',{name:'Add subject',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Basic Maths',exact:true})).toBeVisible();
  await page.getByText('Add a course to Basic Maths',{exact:true}).click();
  const course=page.locator('details').filter({has:page.getByText('Add a course to Basic Maths',{exact:true})}).last();
  await course.getByLabel('Course / topic name').fill('Fractions');
  await course.getByLabel('Lesson content').fill('A fraction describes part of a whole. One half equals two quarters.');
  await course.getByRole('button',{name:'Save course'}).click();
  await expect(page.getByText('Fractions',{exact:true})).toBeVisible();
  await page.getByText('Create a quiz',{exact:true}).click();
  await page.getByLabel('Quiz title').fill('Fresh programming check');
  const topics=['Variables & state','Conditions & boundaries','Loops & execution'];
  const prompts=['After score = 2; copy = score; score = 5, what is copy?','For x = 10, is x > 10 true or false?','What is the sum of the values in range(1, 4)?'];
  const keys=['2','false','6'];
  for(let i=0;i<3;i++){
    if(i)await page.getByRole('button',{name:'Add question',exact:true}).click();
    await page.getByLabel(`Topic for question ${i+1}`).selectOption({label:topics[i]});
    await page.getByLabel(`Question ${i+1} text`).fill(prompts[i]);
    await page.getByLabel(`Answer key for question ${i+1}`).fill(keys[i]);
  }
  await page.getByRole('button',{name:'Save quiz draft'}).click();
  await expect(page.getByText('Draft · Only you can see this quiz.')).toBeVisible();
  const quizUrl=page.url();
  await page.getByRole('button',{name:'Edit draft',exact:true}).click();
  await page.getByLabel('Quiz title').fill('A fresh programming challenge');
  await page.getByRole('button',{name:'Save quiz draft'}).click();
  await expect(page.getByRole('heading',{level:1})).toHaveText('A fresh programming challenge');
  await page.getByRole('button',{name:'Publish to class'}).click();
  await expect(page.getByText('Published to your class.',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.goto('/signup');
  const student='class_student_'+randomUUID().slice(0,8);
  await page.getByLabel('Username',{exact:true}).fill(student);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByLabel('Confirm password').fill(password);
  await page.getByLabel('Student enrollment code').fill(codes.student_code);
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await expect(page).toHaveURL(/\/learner$/);
  await page.getByRole('link',{name:'Subjects & quizzes',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Basic Maths',exact:true})).toBeVisible();
  await expect(page.getByText('Fractions',{exact:true})).toBeVisible();
  await page.getByRole('link',{name:'Open quiz',exact:true}).click();
  await expect(page.getByText('Answer key',{exact:true})).toHaveCount(0);
  for(const [i,answer,reason] of [[1,'2','copy receives the value 2 at assignment. Updating score later does not update copy.'],[2,'true','I think greater than includes equality, so 10 > 10 is true.'],[3,'10','range includes 1, 2, 3 and 4, so the sum is ten.']] as const){
    await page.getByLabel(`Your answer to question ${i}`).fill(answer);
    await page.getByLabel(`Your reasoning for question ${i}`).fill(reason);
  }
  await captureLayouts(page,'18-class-quiz');
  // A failed request and reload must preserve the student's unsaved writing.
  await page.route('**/api/classroom/quizzes/*/submit',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:{message:'Temporary test connection interruption.'}})}),{times:1});
  await page.getByRole('button',{name:'Submit quiz',exact:true}).click();
  await expect(page.getByText('Temporary test connection interruption.')).toBeVisible();
  await page.getByRole('button',{name:'Try again',exact:true}).click();
  await expect(page.getByLabel('Your answer to question 1')).toHaveValue('2');
  await expect(page.getByLabel('Your reasoning for question 3')).toHaveValue('range includes 1, 2, 3 and 4, so the sum is ten.');
  await page.getByRole('button',{name:'Submit quiz',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Your results',exact:true})).toBeVisible({timeout:65000});
  await expect(page.getByText('AI feedback',{exact:true})).toBeVisible();
  const quizId=new URL(quizUrl).pathname.split('/').pop();
  const submitted=(await (await page.request.get(`/api/classroom/quizzes/${quizId}`)).json()).data.submissions[0];
  const originalEvaluation=JSON.stringify(submitted.evaluation);
  await page.getByText('Ask your teacher to review feedback',{exact:true}).click();
  await page.getByLabel('Question to review').selectOption({index:2});
  await page.getByLabel('What should your teacher reconsider?').fill('Please review the partial reasoning about the range boundary.');
  await page.getByRole('button',{name:'Send review request',exact:true}).click();
  await expect(page.getByText('Review history (1)',{exact:true})).toBeVisible();
  await page.getByRole('link',{name:/See your recommended courses/}).click();
  const data=(await (await page.request.get('/api/classroom')).json()).data;
  const programming=data.subjects.find((s:{title:string})=>s.title==='Basic programming');
  expect(programming.courses[0].score).toBeLessThan(programming.courses[2].score);
  expect(programming.courses[2].title).toBe('Variables & state');
  await captureLayouts(page,'19-course-recommendations');
  await page.request.post('/api/auth/login',{data:{username:owner,password}});
  await page.goto(quizUrl);
  await expect(page.getByRole('heading',{name:student,exact:true})).toBeVisible();
  await expect(page.getByText('AI feedback',{exact:true})).toBeVisible();
  await captureLayouts(page,'20-teacher-quiz-results');
  await page.getByText('Review or correct feedback',{exact:true}).click();
  await page.getByLabel('Question to review').selectOption({index:2});
  await page.getByLabel('Answer score (0–100)').fill('0');
  await page.getByLabel('Reasoning score (0–100)').fill('20');
  await page.getByLabel('Feedback for the student').fill('You identified that the range boundary matters. The stop is excluded, so the values are 1, 2, and 3.');
  await page.getByLabel('Concept to revisit (optional)').fill('Exclusive range stop');
  await page.getByLabel('Reason for this review').fill('Award partial reasoning credit for identifying the boundary while preserving the original incorrect answer.');
  await page.getByLabel('Resolve a student request').selectOption({index:1});
  await page.getByRole('button',{name:'Save teacher review',exact:true}).click();
  await expect(page.getByText('Teacher-reviewed feedback',{exact:true}).first()).toBeVisible();
  const reviewed=(await (await page.request.get(`/api/classroom/submissions/${submitted.id}/reviews`)).json()).data;
  expect(JSON.stringify(reviewed.original_evaluation)).toBe(originalEvaluation);
  expect(reviewed.disputes[0].status).toBe('resolved');
  await page.getByText('Review history (2)',{exact:true}).click();
  await expect(page.getByText('Student request · resolved',{exact:true})).toBeVisible();
  await captureLayouts(page,'23-teacher-feedback-review');
  await page.request.post('/api/auth/login',{data:{username:student,password}});
  const corrected=(await (await page.request.get('/api/classroom')).json()).data;
  const correctedProgramming=corrected.subjects.find((s:{title:string})=>s.title==='Basic programming');
  expect(correctedProgramming.courses.find((c:{title:string})=>c.title==='Loops & execution').score).toBe(10);
  expect(errors).toEqual([]);
});
